# Bitwise Operators

# Bitwise operators act on bits and perform bit-by-bit operations. These are used to operate on binary numbers.

# Bitwise Operators in Python are as follows:

#     Bitwise NOT
#     Bitwise Shift
#     Bitwise AND
#     Bitwise XOR
#     Bitwise OR

